import AppKit
import RadixCore

/// Watches the general pasteboard and reports new copies, as the previous
/// build's pasteboard listener did: images are persisted to the managed images
/// directory, copied files are copied aside, text is reported as-is.
@MainActor
final class ClipboardMonitor {
  /// Copied text and the file URL string of the app that was frontmost.
  var onText: ((String, String?) -> Void)?
  /// A copied image or file: display name, local path, source app.
  var onFile: ((_ name: String, _ path: String, _ bundle: String?) -> Void)?

  private static let pollInterval: TimeInterval = 1
  private static let imageTypes: [(type: NSPasteboard.PasteboardType, fileExtension: String)] = [
    (.png, "png"),
    (NSPasteboard.PasteboardType("public.jpeg"), "jpeg"),
    (.tiff, "tiff"),
  ]
  private static let imageFileExtensions: Set<String> = ["png", "jpg", "jpeg"]
  /// Larger image files are recorded by path instead of copied.
  private static let maxCopiedImageBytes = 50 * 1024 * 1024
  /// Markers password managers and similar apps put on copies that must not
  /// be recorded (nspasteboard.org). The previous build recorded them.
  private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
    NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
    NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
    NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
  ]

  private let imagesDirectory: URL
  private var timer: Timer?
  private var changeCount = 0
  private var frontmostBundle: String?
  private var activationObserver: NSObjectProtocol?

  init(imagesDirectory: URL = Paths.pasteboardImagesDirectory) {
    self.imagesDirectory = imagesDirectory
  }

  func start() {
    guard timer == nil else { return }
    do {
      try FileManager.default.createDirectory(
        at: imagesDirectory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
      try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: imagesDirectory.path)
    } catch {
      NSLog("Could not create pasteboard images directory \(imagesDirectory.path): \(error.localizedDescription)")
    }

    changeCount = NSPasteboard.general.changeCount
    frontmostBundle = Self.bundleURLString(of: NSWorkspace.shared.frontmostApplication)

    activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
      forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
    ) { [weak self] notification in
      let app = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
      let bundle = Self.bundleURLString(of: app)
      MainActor.assumeIsolated {
        // Keep the last known app when the activated one can't be resolved.
        if let bundle { self?.frontmostBundle = bundle }
      }
    }

    // Timer blocks run on the main run loop they were scheduled on.
    timer = Timer.scheduledTimer(withTimeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
      MainActor.assumeIsolated { self?.poll() }
    }
  }

  func stop() {
    timer?.invalidate()
    timer = nil
    if let activationObserver {
      NSWorkspace.shared.notificationCenter.removeObserver(activationObserver)
      self.activationObserver = nil
    }
  }

  isolated deinit {
    stop()
  }

  /// The app's file URL string, resolved from its bundle identifier as the
  /// previous build did.
  nonisolated private static func bundleURLString(of app: NSRunningApplication?) -> String? {
    guard let identifier = app?.bundleIdentifier,
      let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: identifier)
    else { return nil }
    return url.absoluteString
  }

  private func poll() {
    let pasteboard = NSPasteboard.general
    guard pasteboard.changeCount != changeCount else { return }
    changeCount = pasteboard.changeCount

    // Radix re-pasting an existing entry is not a new copy.
    if changeCount == PasteboardWrites.lastRadixChangeCount { return }
    if let types = pasteboard.types, types.contains(where: Self.privateTypes.contains) {
      return
    }

    let bundle = frontmostBundle
    // A copied file wins over image data: Finder can put the file's icon on
    // the pasteboard next to the file URL, which isn't what was copied.
    if let data = pasteboard.data(forType: .fileURL) {
      handleFileURL(data, bundle: bundle)
      return
    }

    if persistImageIfPresent(pasteboard, bundle: bundle) { return }

    if let text = pasteboard.string(forType: .string) {
      onText?(text, bundle)
    }
  }

  private func persistImageIfPresent(_ pasteboard: NSPasteboard, bundle: String?) -> Bool {
    for (type, fileExtension) in Self.imageTypes {
      guard let data = pasteboard.data(forType: type) else { continue }
      let fileName = "img_\(UUID().uuidString).\(fileExtension)"
      let destination = imagesDirectory.appendingPathComponent(fileName)
      // Screenshots are megabytes; write off the main thread.
      Task { [weak self] in
        let written = await Task.detached(priority: .utility) {
          Self.writePrivately(data, to: destination)
        }.value
        guard written else { return }
        self?.onFile?(fileName, destination.path, bundle)
      }
      return true
    }
    return false
  }

  /// Image files are copied into the managed directory so the entry survives
  /// the original moving. Every other file is recorded by its original path:
  /// the previous build copied those into the temporary directory, deleting
  /// whatever had the same name there first (and a copied volume root would
  /// have removed the temporary directory itself).
  func handleFileURL(_ data: Data, bundle: String?) {
    guard let url = URL(dataRepresentation: data, relativeTo: nil), url.isFileURL else {
      NSLog("Pasteboard file URL could not be decoded")
      return
    }
    let values = try? url.resourceValues(forKeys: [.isRegularFileKey, .fileSizeKey])
    let isImageFile =
      Self.imageFileExtensions.contains(url.pathExtension.lowercased()) && values?.isRegularFile == true
      && (values?.fileSize ?? .max) <= Self.maxCopiedImageBytes
    guard isImageFile else {
      let name = url.lastPathComponent.isEmpty ? url.path : url.lastPathComponent
      onFile?(name, url.path, bundle)
      return
    }

    let name = "img_\(UUID().uuidString).\(url.pathExtension.lowercased())"
    let destination = imagesDirectory.appendingPathComponent(name)
    Task { [weak self] in
      let copied = await Task.detached(priority: .utility) { Self.copyPrivately(url, to: destination) }.value
      guard copied else { return }
      self?.onFile?(name, destination.path, bundle)
    }
  }

  /// Copied images can be screenshots of anything, so they are readable by
  /// this user only.
  nonisolated private static func writePrivately(_ data: Data, to destination: URL) -> Bool {
    guard FileManager.default.createFile(atPath: destination.path, contents: data, attributes: privateFile) else {
      NSLog("Could not persist copied image to \(destination.path)")
      return false
    }
    return true
  }

  nonisolated private static func copyPrivately(_ source: URL, to destination: URL) -> Bool {
    do {
      try FileManager.default.copyItem(at: source, to: destination)
      try FileManager.default.setAttributes(privateFile, ofItemAtPath: destination.path)
      return true
    } catch {
      NSLog("Could not copy \(source.lastPathComponent) from the pasteboard: \(error.localizedDescription)")
      return false
    }
  }

  nonisolated private static var privateFile: [FileAttributeKey: Any] { [.posixPermissions: 0o600] }
}
